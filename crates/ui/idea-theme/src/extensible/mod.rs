//! Extensible theming — tones and tone-aware surface recipes.
//!
//! idea-ui's components declare their styled sections with
//! `component_styles!`; this module is the open part of the THEME those
//! slots draw from:
//!
//! - [`Tone`] — a semantic palette (Primary, Danger, an app's Brand…).
//!   Every tone-aware component renders an arm per registered tone
//!   ([`register_tone`], [`semantic_tones`]); `app_theme! { tones: [...] }`
//!   registers an app's tones when the theme installs.
//! - [`Variant`] — a tone-aware surface recipe (filled, soft, outlined…).
//!   [`tone_variant_arms`] renders a recipe over a tone set into a slot's
//!   `variant` axis arms, so an app variant value
//!   (`ButtonVariant::define("raised")`) gets a tone-aware look from a
//!   restyle.
//!
//! Sizes, shapes and typography kinds are each component's own axes
//! (generated by its `component_styles!`), not traits here.

