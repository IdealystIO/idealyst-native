//! Index `content/` into `OUT_DIR/content_generated.rs`: the server
//! instructions, every `content/skills/*.md` and every
//! `content/recipes/*.rs`, each as a `(slug, include_str!(…))` pair.
//! Parsing (front-matter, recipe headers) happens at runtime in
//! `src/content.rs`, where it is unit-tested; this script only lists
//! files, so a new skill or recipe needs no registration anywhere.

use std::fs;
use std::path::{Path, PathBuf};

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let content = manifest.join("content");
    println!("cargo:rerun-if-changed={}", content.display());

    let mut out = String::from("// AUTO-GENERATED by build.rs from content/ — DO NOT EDIT.\n\n");
    let instructions = content.join("instructions.md");
    println!("cargo:rerun-if-changed={}", instructions.display());
    out.push_str(&format!(
        "pub(crate) const INSTRUCTIONS: &str = include_str!({:?});\n\n",
        instructions.display().to_string()
    ));
    out.push_str(&list("SKILLS", &content.join("skills"), "md"));
    out.push_str(&list("RECIPES", &content.join("recipes"), "rs"));

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("content_generated.rs"), out).expect("write content_generated.rs");
}

fn list(name: &str, dir: &Path, ext: &str) -> String {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut files: Vec<PathBuf> = fs::read_dir(dir)
        .unwrap_or_else(|e| panic!("read {}: {e}", dir.display()))
        .map(|e| e.expect("dir entry").path())
        .filter(|p| p.extension().and_then(|s| s.to_str()) == Some(ext))
        .collect();
    files.sort();
    let mut s = format!("pub(crate) const {name}: &[(&str, &str)] = &[\n");
    for p in &files {
        println!("cargo:rerun-if-changed={}", p.display());
        let slug = p.file_stem().unwrap().to_str().unwrap();
        s.push_str(&format!("    ({slug:?}, include_str!({:?})),\n", p.display().to_string()));
    }
    s.push_str("];\n\n");
    s
}
