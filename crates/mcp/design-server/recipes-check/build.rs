//! Generate one `#[path]` module per `../content/recipes/*.rs`, so every
//! recipe the design MCP serves is compiled here — a new recipe file is
//! picked up with no list to keep in step.

use std::fs;
use std::path::PathBuf;

fn main() {
    let manifest = PathBuf::from(std::env::var("CARGO_MANIFEST_DIR").unwrap());
    let dir = manifest.join("../content/recipes").canonicalize().expect("content/recipes");
    println!("cargo:rerun-if-changed={}", dir.display());

    let mut names: Vec<(String, PathBuf)> = fs::read_dir(&dir)
        .expect("read content/recipes")
        .map(|e| e.expect("dir entry").path())
        .filter(|p| p.extension().and_then(|s| s.to_str()) == Some("rs"))
        .map(|p| (p.file_stem().unwrap().to_str().unwrap().to_string(), p))
        .collect();
    names.sort();

    let mut out = String::from("// AUTO-GENERATED by build.rs from content/recipes/*.rs.\n\n");
    for (name, path) in &names {
        println!("cargo:rerun-if-changed={}", path.display());
        out.push_str(&format!("#[path = {:?}]\npub mod {name};\n", path.display().to_string()));
    }
    out.push_str("\n/// Every recipe module's name and `app` entry.\n");
    out.push_str("pub const RECIPES: &[(&str, fn() -> runtime_core::Element)] = &[\n");
    for (name, _) in &names {
        out.push_str(&format!("    ({name:?}, {name}::app),\n"));
    }
    out.push_str("];\n");

    let out_dir = PathBuf::from(std::env::var("OUT_DIR").unwrap());
    fs::write(out_dir.join("recipes_generated.rs"), out).expect("write recipes_generated.rs");
}
