//! Preminted-styles build wiring — the CLI side of the premint
//! pipeline (see `runtime_core::premint` for the registry, the
//! `premint-dump` crate for CSS assembly, and `StyleSource::Preminted`
//! for the runtime arm).
//!
//! Two coordinated halves, glued together by nothing but a shared
//! class-naming scheme (names derive from each sheet's content hash,
//! computed inside the `stylesheet!` macro — no manifest):
//!
//! 1. **Dump build** (this module): an ephemeral NATIVE bin crate that
//!    links the app rlib with `RUSTFLAGS="--cfg idealyst_premint_dump"`
//!    and the facade's `style-dump` feature, so every `stylesheet!`
//!    in the app and its dependency tree registers into the
//!    `PREMINT_SHEETS` distributed slice. Running it emits every
//!    sheet's full variant space as CSS, which the caller writes into
//!    `pkg/premint.css` (content-addressed with the rest of `pkg/` by
//!    `fingerprint_pkg`).
//! 2. **Shipped wasm build**: compiled with
//!    `RUSTFLAGS="--cfg idealyst_premint"` (see `cargo_build_wasm`),
//!    which flips the macro-generated `into_style_source` to return
//!    `StyleSource::Preminted { class }` for all-constant applications
//!    — the walker then stamps the class instead of invoking the style
//!    engine, and the browser resolves it against the emitted `.css`.

use anyhow::{Context, Result};
use build_ios::{FrameworkSource, Manifest};
use std::fs;
use std::path::Path;
use std::process::Command;

/// Pre-fingerprint filename of the emitted stylesheet inside `pkg/`.
/// `fingerprint_pkg` content-addresses it like every other pkg file.
pub const PREMINT_CSS_NAME: &str = "premint.css";

/// Generate the ephemeral dump wrapper, build it natively, run it, and
/// return the emitted CSS. `wrapper_root` is the per-project web build
/// dir (the parent of the wasm `wrapper/`); the dump crate lands in a
/// `premint-dump/` sibling.
pub(crate) fn generate_and_run_dump(
    wrapper_root: &Path,
    project_dir: &Path,
    source: &FrameworkSource,
    manifest: &Manifest,
) -> Result<String> {
    let dump_dir = wrapper_root.join("premint-dump");
    generate_dump_wrapper(&dump_dir, project_dir, source, manifest)?;

    // NOTE: no shared-target-dir `.cargo/config.toml` here, unlike the
    // SSR wrapper. The dump build sets custom RUSTFLAGS, and cargo
    // fingerprints every unit on RUSTFLAGS — sharing the project's
    // `target/` would invalidate the app's normal dev/test artifacts on
    // every premint build (and vice versa), a full-workspace rebuild
    // each direction. An isolated target dir costs one cold build of
    // the native dep tree, then caches across premint builds.
    let existing = std::env::var("RUSTFLAGS").unwrap_or_default();
    let rustflags = if existing.is_empty() {
        "--cfg idealyst_premint_dump".to_string()
    } else {
        format!("{existing} --cfg idealyst_premint_dump")
    };
    eprintln!("[build-web] premint dump: cargo build (in {})", dump_dir.display());
    let status = Command::new("cargo")
        .arg("build")
        .current_dir(&dump_dir)
        .env("RUSTFLAGS", rustflags)
        .status()
        .with_context(|| "spawn `cargo` — is it on your PATH?")?;
    if !status.success() {
        anyhow::bail!("cargo build failed for the premint dump wrapper at {}", dump_dir.display());
    }

    let out_css = dump_dir.join("premint-out.css");
    let binary = dump_dir.join("target/debug/premint-dump");
    let status = Command::new(&binary)
        .arg(&out_css)
        .status()
        .with_context(|| format!("run premint dump binary {}", binary.display()))?;
    if !status.success() {
        anyhow::bail!("premint dump binary failed ({})", binary.display());
    }
    fs::read_to_string(&out_css)
        .with_context(|| format!("read premint dump output {}", out_css.display()))
}

/// Materialize the dump wrapper crate. Idempotent — rewritten every
/// build, same as the wasm/SSR wrappers.
fn generate_dump_wrapper(
    dump_dir: &Path,
    project_dir: &Path,
    source: &FrameworkSource,
    manifest: &Manifest,
) -> Result<()> {
    fs::create_dir_all(dump_dir.join("src"))
        .with_context(|| format!("create {}", dump_dir.display()))?;

    let cargo_toml = format!(
        r#"# GENERATED by `idealyst build --web --premint`. Do not edit —
# rewritten every build.

# Standalone project even though it lives under the main workspace's
# `target/idealyst/...` (same reason as the wasm wrapper).
[workspace]

[package]
name = "{name}-premint-dump"
version = "0.0.1"
edition = "2021"

[[bin]]
name = "premint-dump"
path = "src/main.rs"

[dependencies]
# `style-dump` provides `runtime_core::premint` (the distributed slice
# the app's `stylesheet!` registrations target under
# `cfg(idealyst_premint_dump)`) and unifies onto every crate in the
# graph. `runtime-core/style-dump` forwards to
# `runtime-vocabulary/style-dump`: the `stylesheet!` expansion emits
# `::runtime_core::premint::…`, and the macro retarget rewrites that
# into glue, so the dump registry has to have a glue home.
runtime-core = {fcore_dep}
# The dump builds the app's element tree, and building it creates
# signals — which resolve the AMBIENT world. The entry below wraps the
# build in an explicit `World`.
runtime-world = {world_dep}
# The route crawl (see main.rs) drives the navigator's headless
# deep-link slot + route collector, and seeds the viewport. All three are
# `runtime-shared` thread-level state that the facade does not re-export
# — SSG reaches them the same way, straight off the substrate crate.
runtime-shared = {shared_dep}
premint-dump = {pdump_dep}
# The dump MOUNTS the app (see main.rs) and needs a native `Host` to mount
# against. `host-mock` implements `Host` + all 30 capability traits over a
# recording op log — it exists for exactly this (unit-testing anything that
# goes through `runtime_scene::realize`), so the dump reuses it rather than
# growing a second headless backend.
host-mock = {hostmock_dep}
{user_name} = {{ path = "{user_path}" }}

# The dump binary runs once per build and is thrown away — debuginfo
# would only bloat this wrapper's isolated target dir, which holds a
# full native build of the app's dependency tree (gigabytes of DWARF
# on a large app; it filled a disk in testing). Incremental caches
# doubly so.
[profile.dev]
debug = false
incremental = false
{patch_block}"#,
        name = manifest.name,
        fcore_dep = source.dep("crates/runtime/core", &["style-dump"]),
        world_dep = source.dep("crates/runtime/world", &[]),
        shared_dep = source.dep("crates/runtime/shared", &[]),
        pdump_dep = source.dep("crates/tools/premint-dump", &[]),
        hostmock_dep = source.dep("crates/dev/host-mock", &[]),
        user_name = manifest.name,
        user_path = project_dir.display(),
        patch_block = source.patch_block(),
    );

    let main_rs = format!(
        r#"// GENERATED premint dump entry. Emits every registered sheet's
// preminted CSS to the path given as argv[1].

use runtime_shared::primitives::navigator::{{
    enable_route_collector, set_initial_path, take_route_collector,
}};
use std::collections::{{HashSet, VecDeque}};

/// Build + MOUNT the app once, with `path` as the deep-link the root
/// navigator opens to. Returns the literal routes discovered during the
/// mount (nested navigators publish theirs as their parent screen mounts,
/// so the caller loops until the queue drains).
///
/// MOUNT, don't just build. Building alone reaches only the sheets
/// constructed during `app()`; a sheet created at MOUNT — inside a
/// component body, or behind a `move ||` style closure that runs when a
/// node attaches — stays invisible, gets no CSS, and the shipped bundle
/// then stamps a build-time class with nothing behind it. That is a
/// silently unstyled node, and it happened four times before the dump
/// learned to mount: AppShell's scrim/panel/content (144 of 400 catalog
/// elements broken), plus Tooltip's and Spinner's sheets.
///
/// Failures are NOT fatal. A mount can hit anything an app does on
/// attach, and a build step must not start failing because one route
/// dislikes the mock backend. On a panic we keep whatever registered
/// before it and carry on with the next route.
fn visit(path: &str) -> Vec<&'static str> {{
    // Seeded OUTSIDE the world, like the SSR/SSG renderer does: both are
    // thread-level state the navigator handlers peek during mount. The
    // viewport matches SSR's so responsive branches fold the same way
    // here as they do on the server's first paint.
    set_initial_path(Some(path.to_string()));
    runtime_shared::set_viewport_size(runtime_shared::ViewportSize::new(1280.0, 800.0));
    enable_route_collector();

    let ok = std::panic::catch_unwind(std::panic::AssertUnwindSafe(|| {{
        // The app runs inside a `World` because `signal()` / `effect()`
        // resolve the ambient world and abort with "called outside
        // World::enter" otherwise, and essentially every real app body
        // creates a signal while building.
        //
        // A fresh harness (and so a fresh World) per route: route N's
        // reactive state must not leak into route N+1's mount.
        let harness = host_mock::Harness::with_registry({lib}::register_scene_extensions);
        let tree = harness.world.enter(|| {lib}::app());
        let realized = harness.mount(tree);
        // Commit anything staged during mount (write-backs, driver-effect
        // state) — driver effects are where several navigators publish
        // their nested routes.
        harness.flush();
        // Skip destructors. The tree and its world reference reactive
        // thread-locals whose teardown order is unspecified, and this
        // process is thrown away the moment the CSS is written — leaking
        // N route-trees is strictly cheaper than an abort in a build step.
        // The sheets themselves survive regardless: the premint registry
        // holds its own `Rc<StyleSheet>`.
        std::mem::forget(realized);
        std::mem::forget(harness);
    }}))
    .is_ok();

    let discovered = take_route_collector().unwrap_or_default();
    set_initial_path(None);
    if !ok {{
        eprintln!(
            "[premint-dump] warning: mounting route {{path:?}} failed; styles \
             reached only on that route will have no CSS — check for unstyled \
             nodes there, or build with --premint-report."
        );
    }}
    discovered
}}

fn main() {{
    let out = std::env::args().nth(1).expect("usage: premint-dump <out.css>");

    // Walk EVERY literal route, not just `/`. Mounting the initial route
    // reaches the app chrome and that route's screen — a component that
    // first appears on a later page (a Tooltip on /components/tooltip, a
    // Spinner on /components/spinner) registers no sheet, gets no CSS, and
    // ships a dangling class. Same crawl contract as `--ssg`: the route
    // collector harvests each mounting navigator's screen paths, we queue
    // the unrendered literals, and nested navigators fall out of the loop.
    //
    // Force-linking the app crate is a side effect worth naming: a
    // distributed-slice registration only survives the link if the object
    // file carrying it is pulled in, and an otherwise unreferenced rlib can
    // be dropped wholesale.
    let mut queue: VecDeque<String> = VecDeque::from(["/".to_string()]);
    let mut seen: HashSet<String> = HashSet::from(["/".to_string()]);
    let mut skipped: Vec<&'static str> = Vec::new();
    let mut visited = 0usize;

    while let Some(path) = queue.pop_front() {{
        visited += 1;
        for p in visit(&path) {{
            // Parameterized routes need param values the crawl cannot
            // invent — same limitation `--ssg` reports. Their screens'
            // styles are only reached if some literal route mounts them.
            if p.contains(':') {{
                if !skipped.contains(&p) {{
                    skipped.push(p);
                }}
                continue;
            }}
            if seen.insert(p.to_string()) {{
                queue.push_back(p.to_string());
            }}
        }}
    }}

    let css = premint_dump::dump_all_css();
    std::fs::write(&out, &css).expect("write premint css");
    eprintln!("[premint-dump] mounted {{visited}} route(s)");
    if !skipped.is_empty() {{
        eprintln!(
            "[premint-dump] skipped {{}} parameterized route(s); styles unique to \
             them are not preminted: {{:?}}",
            skipped.len(),
            skipped,
        );
    }}
    eprintln!("[premint-dump] {{}} bytes of preminted CSS", css.len());
    // Same reason as the per-route forgets: unspecified TLS teardown order
    // at process exit.
    std::process::exit(0);
}}
"#,
        lib = manifest.lib_name,
    );

    fs::write(dump_dir.join("Cargo.toml"), cargo_toml)?;
    fs::write(dump_dir.join("src/main.rs"), main_rs)?;
    Ok(())
}

#[cfg(test)]
mod dump_wrapper_template_tests {
    //! Shape regression for the generated dump wrapper — ephemeral
    //! generated source, so drift is invisible until a user runs
    //! `--premint`. Pin the load-bearing lines.

    use super::*;
    use build_ios::parse_manifest;

    fn generate_into_temp() -> (tempfile::TempDir, String, String) {
        let tmp = tempfile::tempdir().expect("tempdir");
        let project_dir = tmp.path().join("demo-app");
        fs::create_dir_all(&project_dir).unwrap();
        fs::write(
            project_dir.join("Cargo.toml"),
            "[package]\nname = \"demo-app\"\nversion = \"0.0.1\"\n",
        )
        .unwrap();
        let manifest = parse_manifest(&project_dir).expect("parse manifest");
        let dump_dir = tmp.path().join("premint-dump");
        let source = FrameworkSource::Workspace { root: tmp.path().join("fw") };
        generate_dump_wrapper(&dump_dir, &project_dir, &source, &manifest).expect("generate");
        let cargo = fs::read_to_string(dump_dir.join("Cargo.toml")).unwrap();
        let main = fs::read_to_string(dump_dir.join("src/main.rs")).unwrap();
        (tmp, cargo, main)
    }

    #[test]
    fn dump_wrapper_enables_style_dump_and_links_app() {
        let (_tmp, cargo, main) = generate_into_temp();
        assert!(
            cargo.contains("features = [\"style-dump\"]"),
            "runtime-core must carry style-dump so the registry exists:\n{cargo}"
        );
        // The dep line itself. A generated Cargo.toml is not
        // type-checked, so this assertion is the only thing standing
        // between a rename and a broken `--premint` build (baseline doc
        // §7.7). Scope to `[dependencies]` so the `[patch]` block can't
        // satisfy it by accident.
        let deps_section = cargo
            .split("[patch.")
            .next()
            .expect("cargo.toml has a dependencies half");
        assert!(
            deps_section.contains("runtime-core = "),
            "dump wrapper must depend on runtime-core:\n{cargo}"
        );
        assert!(cargo.contains("premint-dump = "), "dump assembly crate dep:\n{cargo}");
        assert!(cargo.contains("host-mock = "), "dump needs a Host to mount against:\n{cargo}");
        assert!(cargo.contains("demo-app = { path = "), "app dep line:\n{cargo}");
        assert!(
            main.contains("demo_app::app()"),
            "the wrapper must force-link the app via app():\n{main}"
        );
        // Building outside a world aborts the dump the moment the app
        // body creates a signal.
        assert!(
            main.contains("harness.world.enter("),
            "the app tree must be built inside a World:\n{main}"
        );
        // THE load-bearing one. Building the tree reaches only the sheets
        // constructed during `app()`; a sheet created at MOUNT gets no CSS,
        // and the shipped bundle then stamps a build-time class with
        // nothing behind it — a silently unstyled node. Four real
        // breakages before the dump learned to mount (AppShell's
        // scrim/panel/content, Tooltip, Spinner), and none of them failed
        // a build or logged anything.
        assert!(
            main.contains("harness.mount(tree)"),
            "the dump must MOUNT the app, not just build it:\n{main}"
        );
        assert!(
            main.contains("Harness::with_registry(demo_app::register_scene_extensions)"),
            "the mount must install the app's own scene extensions, or a \
             third-party payload panics at realize and takes the dump with \
             it:\n{main}"
        );
        // A build step must not start failing because a component dislikes
        // the mock backend; degrade to build-only collection instead.
        assert!(
            main.contains("catch_unwind"),
            "a mount failure must not fail the build:\n{main}"
        );
        assert!(main.contains("premint_dump::dump_all_css()"), "dump call:\n{main}");
        assert!(
            cargo.contains("debug = false"),
            "dump wrapper must strip debuginfo (target-dir disk blowup):\n{cargo}"
        );
    }

    #[test]
    fn dump_wrapper_crawls_every_literal_route() {
        let (_tmp, cargo, main) = generate_into_temp();
        // Mounting only `/` reaches the app chrome and the initial screen.
        // A component that first appears on a later page registers no
        // sheet, gets no CSS, and the shipped bundle stamps a class with
        // nothing behind it — verified against Spinner, whose class stayed
        // absent from the CSS until the dump learned to crawl.
        assert!(
            main.contains("set_initial_path(Some(path.to_string()))"),
            "each route must be mounted as the navigator's deep-link:\n{main}"
        );
        assert!(
            main.contains("enable_route_collector()") && main.contains("take_route_collector()"),
            "route discovery reuses the SSG collector:\n{main}"
        );
        assert!(
            main.contains("queue.push_back"),
            "discovered routes must be queued so nested navigators are \
             reached too:\n{main}"
        );
        // The collector yields patterns, not paths; `/user/:id` cannot be
        // mounted without a param value the crawl has no way to invent.
        assert!(
            main.contains("p.contains(':')"),
            "parameterized routes must be skipped, not mounted:\n{main}"
        );
        // A fresh World per route — route N's reactive state must not
        // leak into route N+1's mount.
        assert!(
            main.contains("Harness::with_registry") && main.contains("fn visit(path: &str)"),
            "each route mounts on its own harness:\n{main}"
        );
        assert!(
            cargo.contains("runtime-shared = "),
            "the crawl reaches the navigator slot + viewport off the \
             substrate crate, which the facade does not re-export:\n{cargo}"
        );
    }
}
