//! A hermetic world for running real `cargo` against a generated wrapper,
//! offline: a stub framework checkout (the `Workspace` source), a vendored
//! "crates.io" holding `fakedep` 1.0.0 AND 1.1.0, and an app crate whose
//! lock pins `fakedep` 1.0.0 — so "newest compatible" (what a wrapper that
//! re-resolves gets) and "what the app locked" (what a seeded wrapper
//! gets) disagree, and a test can tell which one a wrapper built.
//!
//! Every builder's `regression_<platform>_wrapper_lock_reresolved_every_run`
//! uses it. Enabled for the sibling build crates' tests by the
//! `test-support` feature.

use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

use crate::{record_resolved_lock, FrameworkSource};

/// One stub crate: `(subpath under the framework root, package name,
/// features it declares)`.
pub type StubCrate<'a> = (&'a str, &'a str, &'a [&'a str]);

/// The crates every wrapper names (the facade and the substrate).
pub const CORE_CRATES: &[StubCrate<'static>] = &[
    ("crates/runtime/core", "runtime-core", &["dev", "catalog"]),
    ("crates/runtime/shared", "runtime-shared", &["robot"]),
];

/// See the module docs.
pub struct LockWorld {
    _tmp: tempfile::TempDir,
    /// Canonical root of the world.
    pub root: PathBuf,
    /// The app crate (`demo`, lib `demo`, features `ssr` / `terminal`).
    pub app: PathBuf,
    /// The stub framework checkout.
    pub fw: PathBuf,
}

/// Write a stub crate with an empty `lib.rs`. `vendored` adds the
/// checksum file a directory source requires.
pub fn stub_crate(dir: &Path, name: &str, version: &str, features: &[&str], vendored: bool) {
    fs::create_dir_all(dir.join("src")).unwrap();
    let feats: String = features.iter().map(|f| format!("{f} = []\n")).collect();
    fs::write(
        dir.join("Cargo.toml"),
        format!("[package]\nname = \"{name}\"\nversion = \"{version}\"\nedition = \"2021\"\n\n[features]\n{feats}"),
    )
    .unwrap();
    fs::write(dir.join("src/lib.rs"), "").unwrap();
    if vendored {
        fs::write(dir.join(".cargo-checksum.json"), r#"{"files":{},"package":null}"#).unwrap();
    }
}

/// The app's `Cargo.lock`, pinning `fakedep` at `fakedep`.
pub fn app_lock(fakedep: &str) -> String {
    format!(
        "# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n\
         [[package]]\nname = \"demo\"\nversion = \"0.1.0\"\ndependencies = [\n \"fakedep\",\n]\n\n\
         [[package]]\nname = \"fakedep\"\nversion = \"{fakedep}\"\nsource = \"registry+https://github.com/rust-lang/crates.io-index\"\n"
    )
}

fn write(path: &Path, contents: &str) {
    fs::create_dir_all(path.parent().unwrap()).unwrap();
    fs::write(path, contents).unwrap();
}

impl LockWorld {
    /// `fw_crates` are the framework crates the wrapper under test names
    /// (beyond [`CORE_CRATES`], which are always present); `vendored` are
    /// extra crates.io stubs it depends on (`objc2`, …) as
    /// `(version, name, features)`.
    pub fn new(fw_crates: &[StubCrate<'_>], vendored: &[StubCrate<'_>]) -> Self {
        let tmp = tempfile::tempdir().expect("tempdir");
        // Canonical: `cargo metadata` reports canonical manifest paths,
        // and the patch block matches them against this root.
        let root = fs::canonicalize(tmp.path()).unwrap();
        let fw = root.join("fw");
        let all: Vec<StubCrate<'_>> = CORE_CRATES.iter().chain(fw_crates).copied().collect();
        let members: Vec<String> = all.iter().map(|(p, _, _)| format!("\"{p}\"")).collect();
        write(&fw.join("Cargo.toml"), &format!("[workspace]\nmembers = [{}]\n", members.join(", ")));
        for (sub, name, feats) in &all {
            stub_crate(&fw.join(sub), name, "1.0.0", feats, false);
        }
        let vendor = root.join("vendor");
        stub_crate(&vendor.join("fakedep-1.0.0"), "fakedep", "1.0.0", &[], true);
        stub_crate(&vendor.join("fakedep-1.1.0"), "fakedep", "1.1.0", &[], true);
        for (version, name, feats) in vendored {
            stub_crate(&vendor.join(format!("{name}-{version}")), name, version, feats, true);
        }
        write(
            &root.join(".cargo/config.toml"),
            "[source.crates-io]\nreplace-with = \"vendored\"\n\n[source.vendored]\ndirectory = \"vendor\"\n",
        );
        let app = root.join("app");
        write(
            &app.join("Cargo.toml"),
            "[package]\nname = \"demo\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\nfakedep = \"1\"\n\n[features]\nssr = []\nterminal = []\n",
        );
        write(&app.join("src/lib.rs"), "");
        write(&app.join("Cargo.lock"), &app_lock("1.0.0"));
        Self { _tmp: tmp, root, app, fw }
    }

    /// The framework source a generator should use: this world's checkout.
    pub fn source(&self) -> FrameworkSource {
        FrameworkSource::Workspace { root: self.fw.clone() }
    }

    /// Where a generator would put `<platform…>` for the app.
    pub fn wrapper_dir(&self, rel: &str) -> PathBuf {
        self.app.join("target/idealyst/demo").join(rel)
    }

    /// Move the app's lock to pin `fakedep` at `version`.
    pub fn set_app_lock(&self, version: &str) {
        fs::write(self.app.join("Cargo.lock"), app_lock(version)).unwrap();
    }

    /// The version of `fakedep` the wrapper at `wrapper` resolves, via real
    /// cargo (offline: everything comes from the vendored dir) — then what
    /// a wrapper build does after cargo exits ([`record_resolved_lock`]).
    pub fn resolved_fakedep(&self, wrapper: &Path) -> String {
        let out = Command::new("cargo")
            .args(["metadata", "--offline", "--format-version", "1"])
            .current_dir(wrapper)
            .output()
            .expect("run cargo metadata");
        record_resolved_lock(wrapper).unwrap();
        assert!(
            out.status.success(),
            "cargo metadata in the wrapper failed (root {}):\n{}",
            self.root.display(),
            String::from_utf8_lossy(&out.stderr)
        );
        let meta: serde_json::Value = serde_json::from_slice(&out.stdout).unwrap();
        let versions: Vec<&str> = meta["packages"]
            .as_array()
            .unwrap()
            .iter()
            .filter(|p| p["name"] == "fakedep")
            .filter_map(|p| p["version"].as_str())
            .collect();
        assert_eq!(versions.len(), 1, "exactly one fakedep in the graph: {versions:?}");
        versions[0].to_string()
    }

    /// The `[build] target-dir` the wrapper's `.cargo/config.toml` names.
    pub fn configured_target_dir(wrapper: &Path) -> PathBuf {
        let cfg = fs::read_to_string(wrapper.join(".cargo/config.toml")).expect("wrapper .cargo/config.toml");
        let parsed: toml::Value = toml::from_str(&cfg).expect("valid TOML");
        let dir = parsed["build"]["target-dir"].as_str().expect("build.target-dir");
        let dir = PathBuf::from(dir);
        if dir.is_absolute() { dir } else { wrapper.join(dir) }
    }

    /// The assertions every `regression_<platform>_wrapper_lock_reresolved_every_run`
    /// makes, with `generate` regenerating the wrapper at `wrapper`:
    /// it resolves the app's locked version, keeps doing so across
    /// regeneration, and follows the app's lock when it moves — both ways.
    pub fn assert_wrapper_follows_app_lock(&self, wrapper: &Path, mut generate: impl FnMut()) {
        generate();
        assert_eq!(self.resolved_fakedep(wrapper), "1.0.0", "the wrapper must resolve the app's locked version");
        // Regenerating with nothing changed keeps the lock cargo wrote —
        // which, unlike a deleted one, still pins the app's version.
        generate();
        assert!(wrapper.join("Cargo.lock").is_file(), "the wrapper's lock must survive regeneration");
        assert_eq!(self.resolved_fakedep(wrapper), "1.0.0");
        // The app's lock moves; the wrapper follows. And back down:
        // content, not mtime, decides.
        self.set_app_lock("1.1.0");
        generate();
        assert_eq!(self.resolved_fakedep(wrapper), "1.1.0", "the wrapper must follow the app's lock");
        self.set_app_lock("1.0.0");
        generate();
        assert_eq!(self.resolved_fakedep(wrapper), "1.0.0");
    }

    /// The assertions every `<platform>_wrapper_target_dir_is_private` makes.
    pub fn assert_private_target_dir(&self, wrapper: &Path, project_target: &Path) {
        let configured = Self::configured_target_dir(wrapper);
        assert_eq!(configured, crate::wrapper_target_dir(wrapper), "config must name the private dir");
        assert!(configured.starts_with(wrapper), "{} not under the wrapper", configured.display());
        assert_ne!(configured, project_target, "the wrapper must not share the project's target dir");
        let cfg = fs::read_to_string(wrapper.join(".cargo/config.toml")).unwrap();
        assert!(cfg.contains("[registries."), "the registry must be defined for `[patch.idealyst]`: {cfg}");
    }
}
