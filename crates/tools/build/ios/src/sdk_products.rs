//! Building a package an SDK declares as an extra build product.
//!
//! Some SDKs ship code the app does not link: a CoreAudio plug-in or a
//! system extension inside the macOS `.app`, a COM DLL beside the Windows
//! `.exe`. The SDK names the package that carries it (a dependency, so it
//! is in the app's graph and locked with it) and the features that turn
//! the product on; the platform build tool builds that package on its own,
//! for the app's target, and places the result.
//!
//! The build runs in a **shim** workspace, `<wrapper>/sdk-products/<package>/`,
//! whose one dependency is the package (by path, at the source directory
//! the app's graph resolved) with the declared features:
//!
//! - Cargo refuses `--features` for a package outside the workspace being
//!   built ("cannot specify features for packages outside of workspace"),
//!   and the package is always outside the wrapper's. Features a dependency
//!   entry enables are honoured by `cargo build -p <package>`.
//! - Declaring the dependency in the wrapper itself would unify those
//!   features into the app's own build of the package, linking the product
//!   code into the app.
//!
//! The shim sits under the wrapper so cargo finds the wrapper's
//! `.cargo/config.toml` (registry, per-target rustflags), seeds its lock
//! from the app's ([`seed_wrapper_lockfile`]) and builds into the wrapper's
//! private target dir under its own [`target_gc`] record, so the wrapper's
//! prune keeps its units and its prune keeps the wrapper's.

use std::path::{Path, PathBuf};
use std::process::Command;

use anyhow::Result;

use crate::{build_wrapper, seed_wrapper_lockfile, target_gc};

/// Which target of the package is the product.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum ProductTarget<'a> {
    /// The library target (`--lib`) — a `cdylib`.
    Lib,
    /// The named binary target (`--bin <name>`).
    Bin(&'a str),
}

/// One product build.
#[derive(Clone, Debug)]
pub struct ProductBuild<'a> {
    /// Log-line prefix (`build-macos`).
    pub label: &'a str,
    /// The platform wrapper the app was built in.
    pub wrapper_dir: &'a Path,
    /// The wrapper's private target dir.
    pub target_dir: &'a Path,
    /// The app crate, whose `Cargo.lock` seeds the shim's.
    pub project_dir: &'a Path,
    /// The wrapper's `[patch]` tables, repeated so the shim resolves the
    /// framework where the wrapper does.
    pub patch_block: &'a str,
    /// The package to build.
    pub package: &'a str,
    /// The package's source directory, from the wrapper's `cargo metadata`.
    pub manifest_dir: &'a Path,
    pub target: ProductTarget<'a>,
    pub features: &'a [String],
    /// Set on the cargo invocation.
    pub env: &'a [(String, String)],
    /// `--target`, or `None` for a host build.
    pub triple: Option<&'a str>,
    pub release: bool,
}

/// The shim workspace for `package` under `wrapper_dir`.
pub fn shim_dir(wrapper_dir: &Path, package: &str) -> PathBuf {
    wrapper_dir.join("sdk-products").join(package)
}

/// A TOML basic string holding `s`, quotes included.
fn toml_str(s: &str) -> String {
    toml::Value::String(s.to_string()).to_string()
}

/// The shim's `Cargo.toml`.
pub fn shim_manifest(package: &str, manifest_dir: &Path, features: &[String], patch_block: &str) -> String {
    let features = features.iter().map(|f| toml_str(f)).collect::<Vec<_>>().join(", ");
    format!(
        "# GENERATED by the idealyst CLI. Do not edit — rewritten every build.\n\
         #\n\
         # Builds `{package}` as an SDK-declared product with its declared\n\
         # features; see `build_ios::sdk_products`.\n\
         \n\
         [workspace]\n\
         \n\
         [package]\n\
         name = \"sdk-product-shim\"\n\
         version = \"0.0.0\"\n\
         edition = \"2021\"\n\
         publish = false\n\
         \n\
         [lib]\n\
         path = \"lib.rs\"\n\
         \n\
         [dependencies]\n\
         {name} = {{ path = {path}, features = [{features}] }}\n\
         {patch_block}",
        name = toml_str(package),
        path = toml_str(&manifest_dir.to_string_lossy()),
    )
}

/// The `cargo` arguments for `b`.
pub fn cargo_args(b: &ProductBuild<'_>) -> Vec<String> {
    let mut args = vec!["build".to_string(), "-p".to_string(), b.package.to_string()];
    match b.target {
        ProductTarget::Lib => args.push("--lib".into()),
        ProductTarget::Bin(name) => args.extend(["--bin".to_string(), name.to_string()]),
    }
    if let Some(t) = b.triple {
        args.extend(["--target".to_string(), t.to_string()]);
    }
    if b.release {
        args.push("--release".into());
    }
    args
}

/// The [`target_gc`] record name for `b`'s build: one per package, target
/// and feature set, distinct from every wrapper variant (those are feature
/// sets alone).
pub fn variant(b: &ProductBuild<'_>) -> String {
    let target = match b.target {
        ProductTarget::Lib => "lib".to_string(),
        ProductTarget::Bin(n) => format!("bin-{n}"),
    };
    let mut features = b.features.to_vec();
    features.sort();
    features.dedup();
    target_gc::variant_key(&format!("sdk-product+{}+{target}+{}", b.package, features.join(",")))
}

/// Generate the shim for `b` (files written through `write`, so a caller
/// with its own durable-write rules keeps them) and build it. Returns the
/// profile dir the product landed in (`<target>[/<triple>]/<profile>`).
pub fn build_product(b: &ProductBuild<'_>, write: &dyn Fn(&Path, &str) -> Result<()>) -> Result<PathBuf> {
    let shim = shim_dir(b.wrapper_dir, b.package);
    std::fs::create_dir_all(&shim)?;
    write(&shim.join("Cargo.toml"), &shim_manifest(b.package, b.manifest_dir, b.features, b.patch_block))?;
    write(&shim.join("lib.rs"), "// GENERATED: the shim has no code of its own.\n")?;
    seed_wrapper_lockfile(&shim, b.project_dir)?;

    let args = cargo_args(b);
    let mut cmd = Command::new("cargo");
    cmd.args(&args);
    for (k, v) in b.env {
        cmd.env(k, v);
    }
    eprintln!("[{}] cargo {} (features: {:?})", b.label, args.join(" "), b.features);
    let spec = target_gc::BuildSpec {
        target_dir: b.target_dir,
        triple: b.triple,
        release: b.release,
        variant: variant(b),
        record_ttl: None,
    };
    build_wrapper(b.label, &shim, &mut cmd, &spec)?;
    Ok(spec.build_profile_dir())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn product<'a>(target: ProductTarget<'a>, features: &'a [String], triple: Option<&'a str>) -> ProductBuild<'a> {
        ProductBuild {
            label: "test",
            wrapper_dir: Path::new("/w/macos"),
            target_dir: Path::new("/w/macos/target"),
            project_dir: Path::new("/p"),
            patch_block: "",
            package: "audio-plugin",
            manifest_dir: Path::new("/reg/audio-plugin-1.0.0"),
            target,
            features,
            env: &[],
            triple,
            release: true,
        }
    }

    /// `cargo build -p <dep> --features …` in the wrapper fails outright
    /// ("cannot specify features for packages outside of workspace"), so
    /// the features ride on the shim's dependency entry and the invocation
    /// carries none.
    #[test]
    fn regression_product_features_ride_on_the_shim_dependency() {
        let features = vec!["plugin".to_string()];
        let b = product(ProductTarget::Lib, &features, Some("x86_64-apple-darwin"));
        let args = cargo_args(&b);
        assert_eq!(args, ["build", "-p", "audio-plugin", "--lib", "--target", "x86_64-apple-darwin", "--release"]);
        assert!(!args.iter().any(|a| a == "--features"));

        let shim: toml::Value = shim_manifest(b.package, b.manifest_dir, &features, "").parse().expect("valid TOML");
        let dep = &shim["dependencies"]["audio-plugin"];
        assert_eq!(dep["path"].as_str(), Some("/reg/audio-plugin-1.0.0"));
        assert_eq!(dep["features"].as_array().unwrap()[0].as_str(), Some("plugin"));
        assert!(shim.get("workspace").is_some(), "the shim is its own workspace");
    }

    #[test]
    fn bin_products_build_the_named_binary() {
        let b = product(ProductTarget::Bin("camera-ext"), &[], None);
        assert_eq!(cargo_args(&b), ["build", "-p", "audio-plugin", "--bin", "camera-ext", "--release"]);
    }

    /// A Windows source path holds backslashes, an invalid escape in a raw
    /// TOML basic string.
    #[test]
    fn shim_manifest_escapes_windows_paths() {
        let toml_text = shim_manifest("dll", Path::new(r"Z:\reg\dll-1.0.0"), &[], "");
        let shim: toml::Value = toml_text.parse().expect("valid TOML");
        assert_eq!(shim["dependencies"]["dll"]["path"].as_str(), Some(r"Z:\reg\dll-1.0.0"));
    }

    /// A real build: the declared feature reaches the package (its source
    /// refuses to compile without it) and the cdylib lands, uplifted, in the
    /// profile dir the call returns.
    #[test]
    fn build_product_builds_the_package_with_its_declared_features() {
        let tmp = tempfile::tempdir().unwrap();
        let dep = tmp.path().join("plugin-src");
        std::fs::create_dir_all(dep.join("src")).unwrap();
        std::fs::write(
            dep.join("Cargo.toml"),
            "[package]\nname = \"demo-plugin\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\
             [lib]\ncrate-type = [\"rlib\", \"cdylib\"]\n[features]\nplugin = []\n",
        )
        .unwrap();
        std::fs::write(
            dep.join("src/lib.rs"),
            "#[cfg(not(feature = \"plugin\"))] compile_error!(\"built without `plugin`\");\n\
             #[no_mangle] pub extern \"C\" fn demo_plugin_marker() -> i32 { 7 }\n",
        )
        .unwrap();
        let wrapper = tmp.path().join("wrapper");
        let target_dir = wrapper.join("target");
        let project = tmp.path().join("app");
        std::fs::create_dir_all(&project).unwrap();
        let features = vec!["plugin".to_string()];
        let b = ProductBuild {
            label: "test",
            wrapper_dir: &wrapper,
            target_dir: &target_dir,
            project_dir: &project,
            patch_block: "",
            package: "demo-plugin",
            manifest_dir: &dep,
            target: ProductTarget::Lib,
            features: &features,
            env: &[],
            triple: None,
            release: false,
        };
        let write = |p: &Path, s: &str| crate::write_if_changed(p, s).map(|_| ());
        let profile = build_product(&b, &write).expect("product build");
        assert_eq!(profile, target_dir.join("debug"));
        let file = format!(
            "{}demo_plugin{}",
            std::env::consts::DLL_PREFIX,
            std::env::consts::DLL_SUFFIX
        );
        assert!(profile.join(&file).is_file(), "{file} not in {}", profile.display());
        assert!(
            profile.join(target_gc::RECORDS_DIR).join(format!("{}.json", variant(&b))).is_file(),
            "the build must record its units under its own variant"
        );
    }

    /// Each product keeps its own record, apart from the wrapper's feature
    /// variants (`default`, `dev`) — or the wrapper's next prune deletes it.
    #[test]
    fn product_variants_never_collide_with_wrapper_variants() {
        let a = vec!["plugin".to_string()];
        let lib = variant(&product(ProductTarget::Lib, &a, None));
        let bin = variant(&product(ProductTarget::Bin("x"), &a, None));
        assert_ne!(lib, bin);
        for wrapper in ["default", "dev", "aas", "aas+dev"] {
            assert_ne!(lib, wrapper);
        }
        assert!(lib.starts_with("sdk-product"), "{lib}");
    }
}
