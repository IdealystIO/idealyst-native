//! Build-time codegen of the live-preview lookups (`OUT_DIR/previews.rs`).
//!
//! Shared by `build.rs` (which runs it, via `#[path]`) and this crate's
//! unit tests. Reads the catalog JSON and emits:
//!
//! - an `unsafe extern "Rust"` block declaring every component preview
//!   and recipe render fn the catalog names by its exported symbol
//!   (`preview` on component and recipe entries, written by the
//!   `previews` emission in `runtime-macros-expand/src/preview_emit.rs`);
//! - `component_preview(symbol)` and `recipe_renderer(symbol)`, mapping a
//!   symbol to a callable.
//!
//! Exported symbols are the one way to reach every component from the
//! wasm bundle: inventory registrations are pruned there, and a component
//! in a private module has no path the docs app could name. A symbol in
//! the catalog whose crate isn't linked is a link error, never a silent
//! gap.

use std::collections::{BTreeMap, BTreeSet, VecDeque};

/// Components that render through a portal to a document-level root: a
/// preview of one escapes the preview box, and an open one covers the
/// docs page with a backdrop nothing on the page can dismiss. Anything
/// that composes one, directly or through other components, is shown
/// without a live preview.
const OVERLAY_COMPONENTS: &[&str] = &["Modal", "Menu", "SubMenu", "Popover", "Tooltip", "HoverCard", "ToastHost"];
/// The primitives those portals are built from — what catches an app's
/// own overlay component.
const OVERLAY_PRIMITIVES: &[&str] = &["overlay", "anchored_overlay"];

fn is_overlay(name: &str) -> bool {
    OVERLAY_COMPONENTS.contains(&name) || OVERLAY_PRIMITIVES.contains(&name)
}

/// A symbol is spliced into generated Rust, so only a plain identifier is
/// accepted (the catalog JSON may come from `IDEALYST_DOCS_CATALOG`).
fn is_ident(s: &str) -> bool {
    let mut chars = s.chars();
    chars.next().is_some_and(|c| c == '_' || c.is_ascii_alphabetic())
        && chars.all(|c| c == '_' || c.is_ascii_alphanumeric())
}

fn str_list(v: &serde_json::Value) -> Vec<String> {
    v.as_array()
        .map(|a| {
            a.iter()
                .filter_map(|e| e.as_str().or_else(|| e["name"].as_str()).map(str::to_string))
                .collect()
        })
        .unwrap_or_default()
}

/// Names of every catalog component that reaches an overlay through its
/// composes graph (including the overlay components themselves).
fn overlay_reaching(cat: &serde_json::Value) -> BTreeSet<String> {
    let mut composes: BTreeMap<String, Vec<String>> = BTreeMap::new();
    for c in cat["components"].as_array().into_iter().flatten() {
        if let Some(name) = c["name"].as_str() {
            composes.entry(name.to_string()).or_default().extend(str_list(&c["composes"]));
        }
    }
    let mut reaching = BTreeSet::new();
    for start in composes.keys() {
        let mut seen = BTreeSet::new();
        let mut queue = VecDeque::from([start.clone()]);
        while let Some(name) = queue.pop_front() {
            if is_overlay(&name) {
                reaching.insert(start.clone());
                break;
            }
            if seen.insert(name.clone()) {
                queue.extend(composes.get(&name).into_iter().flatten().cloned());
            }
        }
    }
    reaching
}

/// The generated `previews.rs` for `cat`.
pub fn previews_source(cat: &serde_json::Value) -> String {
    let overlay = overlay_reaching(cat);

    let mut components: BTreeSet<String> = BTreeSet::new();
    for c in cat["components"].as_array().into_iter().flatten() {
        let (Some(name), Some(symbol)) = (c["name"].as_str(), c["preview"].as_str()) else { continue };
        if is_ident(symbol) && !overlay.contains(name) {
            components.insert(symbol.to_string());
        }
    }

    let mut recipes: BTreeSet<String> = BTreeSet::new();
    for r in cat["recipes"].as_array().into_iter().flatten() {
        let Some(symbol) = r["preview"].as_str() else { continue };
        let uses = str_list(&r["uses"]);
        if is_ident(symbol) && !uses.iter().any(|u| is_overlay(u) || overlay.contains(u)) {
            recipes.insert(symbol.to_string());
        }
    }

    let mut out = String::from(
        "// @generated by build.rs (src/preview_codegen.rs) — live previews. Do not edit.\n",
    );
    out.push_str("#[allow(improper_ctypes, dead_code)]\nunsafe extern \"Rust\" {\n");
    for s in &components {
        out.push_str(&format!("    fn {s}() -> ::runtime_core::previews::Preview;\n"));
    }
    for s in &recipes {
        out.push_str(&format!("    fn {s}() -> ::runtime_core::Element;\n"));
    }
    out.push_str("}\n\n");

    out.push_str(
        "/// The live preview of the component whose catalog entry records\n\
         /// `symbol`, unless it has none (or renders in an overlay).\n\
         pub fn component_preview(symbol: &str) -> Option<fn() -> ::runtime_core::previews::Preview> {\n\
         \x20   match symbol {\n",
    );
    for s in &components {
        // SAFETY: the symbol is a `fn() -> Preview` exported by
        // `#[component]` under the same feature graph this app builds.
        out.push_str(&format!("        {s:?} => Some(|| unsafe {{ {s}() }}),\n"));
    }
    out.push_str("        _ => None,\n    }\n}\n\n");

    out.push_str(
        "/// The live render of the recipe whose catalog entry records\n\
         /// `symbol`, unless it has none (or builds an overlay).\n\
         pub fn recipe_renderer(symbol: &str) -> Option<fn() -> ::runtime_core::Element> {\n\
         \x20   match symbol {\n",
    );
    for s in &recipes {
        out.push_str(&format!("        {s:?} => Some(|| unsafe {{ {s}() }}),\n"));
    }
    out.push_str("        _ => None,\n    }\n}\n");
    out
}

#[cfg(test)]
mod tests {
    use super::*;
    use serde_json::json;

    #[test]
    fn declares_and_maps_every_recorded_symbol() {
        let cat = json!({
            "components": [
                { "name": "Badge", "preview": "__idealyst_preview__app__Badge__3_4", "composes": [] },
                { "name": "Plain", "composes": [] }
            ],
            "recipes": [
                { "name": "badge_basic", "preview": "__idealyst_recipe__app__badge_basic__9_3", "uses": ["Badge"] },
                { "name": "with_args", "uses": ["Badge"] }
            ]
        });
        let src = previews_source(&cat);
        assert!(src.contains("fn __idealyst_preview__app__Badge__3_4() -> ::runtime_core::previews::Preview;"), "{src}");
        assert!(src.contains("\"__idealyst_preview__app__Badge__3_4\" => Some("), "{src}");
        assert!(src.contains("fn __idealyst_recipe__app__badge_basic__9_3() -> ::runtime_core::Element;"), "{src}");
        assert_eq!(src.matches("=> Some(").count(), 2, "entries without a symbol are left out: {src}");
    }

    #[test]
    fn components_reaching_an_overlay_transitively_get_no_preview() {
        let cat = json!({
            "components": [
                { "name": "Modal", "preview": "m", "composes": [{ "name": "overlay", "line": 1 }] },
                { "name": "Confirm", "preview": "c", "composes": [{ "name": "Modal", "line": 1 }] },
                { "name": "Page", "preview": "p", "composes": [{ "name": "Confirm", "line": 1 }] },
                { "name": "Sheet", "preview": "s", "composes": [{ "name": "anchored_overlay", "line": 1 }] },
                { "name": "Card", "preview": "k", "composes": [{ "name": "view", "line": 1 }] }
            ],
            "recipes": [
                { "name": "confirm", "preview": "rc", "uses": ["Confirm"] },
                { "name": "card", "preview": "rk", "uses": ["Card"] }
            ]
        });
        let src = previews_source(&cat);
        for gone in ["\"m\"", "\"c\"", "\"p\"", "\"s\"", "\"rc\""] {
            assert!(!src.contains(gone), "{gone} reaches an overlay: {src}");
        }
        assert!(src.contains("\"k\" => Some(") && src.contains("\"rk\" => Some("), "{src}");
    }

    #[test]
    fn a_symbol_that_is_not_an_identifier_is_never_spliced() {
        let cat = json!({
            "components": [{ "name": "X", "preview": "a(); evil()", "composes": [] }],
            "recipes": []
        });
        assert!(!previews_source(&cat).contains("evil"));
    }
}
