#[derive(Debug, Clone, Copy, PartialEq, Eq)]
enum Style {
    Named,
    Tuple,
    Unit,
}

#[derive(Debug, Clone, PartialEq, Eq)]
struct Field {
    name: String,
    public: bool,
    ty: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
enum Shape {
    /// Only presence matters.
    Plain,
    Struct { style: Style, fields: Vec<Field>, non_exhaustive: bool },
    /// Variant name → its fields rendered as tokens.
    Enum { variants: BTreeMap<String, String>, non_exhaustive: bool },
    /// Item name → is it required (no default)?
    Trait { items: BTreeMap<String, bool> },
}

#[derive(Debug, Clone)]
struct Entry {
    kind: &'static str,
    /// `a::b::Name`, from the crate root; `Type::method` for methods.
    path: String,
    name: String,
    shape: Shape,
}

/// The exported items of one version of a crate.
#[derive(Debug, Default)]
pub struct Surface {
    /// Keyed by `"<kind> <path>"`.
    entries: BTreeMap<String, Entry>,
}

#[derive(Debug, Default)]
struct Module {
    /// Declared `pub mod`.
    public: bool,
    children: BTreeSet<String>,
    /// `(public, entry)` — private items are kept so a `pub use` of one can
    /// be told apart from a `pub use` of nothing.
    items: Vec<(bool, Entry)>,
    /// `pub use` declarations only.
    uses: Vec<UseEntry>,
}

#[derive(Debug, Clone)]
struct UseEntry {
    path: Vec<String>,
    /// `None` for a glob.
    leaf: Option<String>,
}

#[derive(Default)]
struct Walk {
    modules: BTreeMap<Vec<String>, Module>,
    /// `(self type name, entry)` for every `pub` item of an inherent impl.
    methods: Vec<(String, Entry)>,
    /// `#[macro_export]` macros, exported from the root wherever declared.
    macros: Vec<Entry>,
}

/// Parse the crate rooted at `lib_path` and return its exported items.
pub fn surface(src: &Source, lib_path: &str) -> Result<Surface> {
    let mut walk = Walk::default();
    walk.modules.insert(vec![], Module { public: true, ..Default::default() });
    let text = src.files.get(lib_path).with_context(|| format!("{lib_path} not found"))?;
    let file = syn::parse_file(text).with_context(|| format!("parsing {lib_path}"))?;
    let dir = parent(lib_path);
    walk.items(src, &file.items, &[], &dir, lib_path)?;
    Ok(walk.resolve())
}

impl Walk {
    fn items(&mut self, src: &Source, items: &[Item], m: &[String], dir: &str, file: &str) -> Result<()> {
        for item in items {
            match item {
                Item::Mod(im) => {
                    let name = im.ident.to_string();
                    let mut child = m.to_vec();
                    child.push(name.clone());
                    self.modules.entry(m.to_vec()).or_default().children.insert(name.clone());
                    let public = is_pub(&im.vis);
                    self.modules.entry(child.clone()).or_default().public = public;
                    self.push(m, public, entry("mod", m, &name, Shape::Plain));
                    if let Some((_, content)) = &im.content {
                        let sub = join(dir, &name);
                        self.items(src, content, &child, &sub, file)?;
                        continue;
                    }
                    // Out-of-line: `#[path]` is relative to the declaring
                    // file's directory; otherwise `<dir>/<name>.rs` or
                    // `<dir>/<name>/mod.rs`.
                    let candidates = match path_attr(&im.attrs) {
                        Some(p) => vec![normalize(&join(&parent(file), &p))],
                        None => vec![join(dir, &format!("{name}.rs")), join(dir, &format!("{name}/mod.rs"))],
                    };
                    let Some(found) = candidates.into_iter().find(|c| src.files.contains_key(c)) else {
                        continue;
                    };
                    let parsed = syn::parse_file(&src.files[&found]).with_context(|| format!("parsing {found}"))?;
                    // A `mod.rs` (or a `#[path]` file) owns its directory's
                    // children; `foo.rs` owns `foo/`.
                    let sub = if found.ends_with("/mod.rs") || path_attr(&im.attrs).is_some() {
                        parent(&found)
                    } else {
                        found.trim_end_matches(".rs").to_string()
                    };
                    self.items(src, &parsed.items, &child, &sub, &found)?;
                }
                Item::Struct(s) => {
                    let shape = struct_shape(&s.fields, &s.attrs);
                    self.push(m, is_pub(&s.vis), entry("struct", m, &s.ident.to_string(), shape));
                }
                Item::Union(u) => {
                    let shape = Shape::Struct {
                        style: Style::Named,
                        fields: fields_of(&syn::Fields::Named(u.fields.clone())),
                        non_exhaustive: true,
                    };
                    self.push(m, is_pub(&u.vis), entry("union", m, &u.ident.to_string(), shape));
                }
                Item::Enum(e) => {
                    let variants = e
                        .variants
                        .iter()
                        .map(|v| (v.ident.to_string(), variant_fields(&v.fields)))
                        .collect();
                    let shape = Shape::Enum { variants, non_exhaustive: has_attr(&e.attrs, "non_exhaustive") };
                    self.push(m, is_pub(&e.vis), entry("enum", m, &e.ident.to_string(), shape));
                }
                Item::Trait(t) => {
                    let items = t
                        .items
                        .iter()
                        .filter_map(|ti| match ti {
                            syn::TraitItem::Fn(f) => Some((f.sig.ident.to_string(), f.default.is_none())),
                            syn::TraitItem::Const(c) => Some((c.ident.to_string(), c.default.is_none())),
                            syn::TraitItem::Type(ty) => Some((ty.ident.to_string(), ty.default.is_none())),
                            _ => None,
                        })
                        .collect();
                    self.push(m, is_pub(&t.vis), entry("trait", m, &t.ident.to_string(), Shape::Trait { items }));
                }
                Item::Fn(f) => {
                    let name = f.sig.ident.to_string();
                    let public = is_pub(&f.vis);
                    self.push(m, public, entry("fn", m, &name, Shape::Plain));
                    if let Some(props) = component_props(f) {
                        self.push(m, public, entry("struct", m, &format!("{name}Props"), props));
                    }
                }
                Item::Type(t) => self.push(m, is_pub(&t.vis), entry("type", m, &t.ident.to_string(), Shape::Plain)),
                Item::Const(c) => self.push(m, is_pub(&c.vis), entry("const", m, &c.ident.to_string(), Shape::Plain)),
                Item::Static(s) => {
                    self.push(m, is_pub(&s.vis), entry("static", m, &s.ident.to_string(), Shape::Plain))
                }
                Item::Macro(mac) => {
                    if let Some(ident) = &mac.ident {
                        if mac.mac.path.is_ident("macro_rules") && has_attr(&mac.attrs, "macro_export") {
                            self.macros.push(entry("macro", &[], &ident.to_string(), Shape::Plain));
                        }
                    }
                }
                Item::Use(u) if is_pub(&u.vis) => {
                    let mut out = Vec::new();
                    flatten_use(&u.tree, &mut Vec::new(), &mut out);
                    self.modules.entry(m.to_vec()).or_default().uses.extend(out);
                }
                Item::Impl(imp) if imp.trait_.is_none() => {
                    let Type::Path(tp) = &*imp.self_ty else { continue };
                    let Some(seg) = tp.path.segments.last() else { continue };
                    let ty = seg.ident.to_string();
                    for ii in &imp.items {
                        let (vis, name) = match ii {
                            syn::ImplItem::Fn(f) => (&f.vis, f.sig.ident.to_string()),
                            syn::ImplItem::Const(c) => (&c.vis, c.ident.to_string()),
                            _ => continue,
                        };
                        if is_pub(vis) {
                            let e = Entry {
                                kind: "method",
                                path: format!("{ty}::{name}"),
                                name: format!("{ty}::{name}"),
                                shape: Shape::Plain,
                            };
                            self.methods.push((ty.clone(), e));
                        }
                    }
                }
                _ => {}
            }
        }
        Ok(())
    }

    fn push(&mut self, m: &[String], public: bool, e: Entry) {
        self.modules.entry(m.to_vec()).or_default().items.push((public, e));
    }

    /// Resolve a `use` path written in module `from` to a module path, or
    /// `None` when it leaves the crate (or names nothing we know).
    fn module_at(&self, from: &[String], segs: &[String]) -> Option<Vec<String>> {
        let mut cur: Vec<String>;
        let mut rest = segs;
        match segs.first().map(String::as_str) {
            Some("crate") => {
                cur = vec![];
                rest = &segs[1..];
            }
            Some("self") => {
                cur = from.to_vec();
                rest = &segs[1..];
            }
            Some("super") => {
                cur = from.to_vec();
                while rest.first().map(String::as_str) == Some("super") {
                    cur.pop()?;
                    rest = &rest[1..];
                }
            }
            Some(first) => {
                // 2018 paths: a bare first segment is a child module of
                // `from`, or else another crate.
                if !self.modules.get(from).is_some_and(|md| md.children.contains(first)) {
                    return None;
                }
                cur = from.to_vec();
            }
            None => cur = from.to_vec(),
        }
        for s in rest {
            if !self.modules.get(&cur).is_some_and(|md| md.children.contains(s)) {
                return None;
            }
            cur.push(s.clone());
        }
        Some(cur)
    }

    fn resolve(self) -> Surface {
        // Fixpoint: a module is reachable from the root through `pub mod`
        // declarations, or by being glob- or name-re-exported from a
        // reachable module; a private item is exported when a reachable
        // module re-exports it by name.
        let mut reachable: BTreeSet<Vec<String>> = BTreeSet::from([vec![]]);
        let mut named: BTreeSet<(Vec<String>, String)> = BTreeSet::new();
        let mut external: Vec<Entry> = Vec::new();
        loop {
            let before = (reachable.len(), named.len());
            external.clear();
            for m in reachable.clone() {
                let Some(md) = self.modules.get(&m) else { continue };
                for c in &md.children {
                    let mut cp = m.clone();
                    cp.push(c.clone());
                    if self.modules.get(&cp).is_some_and(|x| x.public) {
                        reachable.insert(cp);
                    }
                }
                for u in &md.uses {
                    match &u.leaf {
                        None => match self.module_at(&m, &u.path) {
                            Some(t) => {
                                reachable.insert(t);
                            }
                            None => external.push(entry("re-export", &m, &format!("{}::*", u.path.join("::")), Shape::Plain)),
                        },
                        Some(leaf) => {
                            let target = self.module_at(&m, &u.path).filter(|t| {
                                let md = &self.modules[t];
                                md.children.contains(leaf) || md.items.iter().any(|(_, e)| &e.name == leaf)
                            });
                            match target {
                                Some(t) => {
                                    let mut cp = t.clone();
                                    cp.push(leaf.clone());
                                    if self.modules.contains_key(&cp) {
                                        reachable.insert(cp);
                                    }
                                    named.insert((t, leaf.clone()));
                                }
                                None => {
                                    let mut full = u.path.clone();
                                    full.push(leaf.clone());
                                    external.push(entry("re-export", &m, &full.join("::"), Shape::Plain))
                                }
                            }
                        }
                    }
                }
            }
            if (reachable.len(), named.len()) == before {
                break;
            }
        }

        let mut s = Surface::default();
        fn add(s: &mut Surface, e: &Entry) {
            s.entries.entry(format!("{} {}", e.kind, e.path)).or_insert_with(|| e.clone());
        }
        for (m, md) in &self.modules {
            for (public, e) in &md.items {
                if *public && (reachable.contains(m) || named.contains(&(m.clone(), e.name.clone()))) {
                    add(&mut s, e);
                }
            }
        }
        for e in self.macros.iter().chain(&external) {
            add(&mut s, e);
        }
        let types: BTreeSet<String> = s
            .entries
            .values()
            .filter(|e| matches!(e.kind, "struct" | "enum" | "union" | "type"))
            .map(|e| e.name.clone())
            .collect();
        for (ty, e) in &self.methods {
            if types.contains(ty) {
                add(&mut s, e);
            }
        }
        s
    }
}

fn entry(kind: &'static str, m: &[String], name: &str, shape: Shape) -> Entry {
    let mut path = m.to_vec();
    path.push(name.to_string());
    Entry { kind, path: path.join("::"), name: name.to_string(), shape }
}

fn flatten_use(tree: &UseTree, prefix: &mut Vec<String>, out: &mut Vec<UseEntry>) {
    match tree {
        UseTree::Path(p) => {
            prefix.push(p.ident.to_string());
            flatten_use(&p.tree, prefix, out);
            prefix.pop();
        }
        UseTree::Name(n) => out.push(UseEntry { path: prefix.clone(), leaf: Some(n.ident.to_string()) }),
        // `pub use x::Foo as Bar` exports `Bar`, but it is `Foo` that has to
        // be found; the public name of a renamed item is tracked by `Foo`'s
        // own entry.
        UseTree::Rename(r) => out.push(UseEntry { path: prefix.clone(), leaf: Some(r.ident.to_string()) }),
        UseTree::Glob(_) => out.push(UseEntry { path: prefix.clone(), leaf: None }),
        UseTree::Group(g) => {
            for t in &g.items {
                flatten_use(t, prefix, out);
            }
        }
    }
}

fn is_pub(v: &Visibility) -> bool {
    matches!(v, Visibility::Public(_))
}

fn has_attr(attrs: &[Attribute], name: &str) -> bool {
    attrs.iter().any(|a| a.path().is_ident(name))
}

fn path_attr(attrs: &[Attribute]) -> Option<String> {
    attrs.iter().find(|a| a.path().is_ident("path")).and_then(|a| match &a.meta {
        syn::Meta::NameValue(nv) => match &nv.value {
            syn::Expr::Lit(syn::ExprLit { lit: syn::Lit::Str(s), .. }) => Some(s.value()),
            _ => None,
        },
        _ => None,
    })
}

fn fields_of(fields: &syn::Fields) -> Vec<Field> {
    fields
        .iter()
        .enumerate()
        .map(|(i, f)| Field {
            name: f.ident.as_ref().map(|i| i.to_string()).unwrap_or_else(|| i.to_string()),
            public: is_pub(&f.vis),
            ty: f.ty.to_token_stream().to_string(),
        })
        .collect()
}

/// A variant's fields as `name: ty` pairs. Attributes are left out: a doc
/// comment or a `#[serde]` rename on a variant field is not an API change.
fn variant_fields(fields: &syn::Fields) -> String {
    let open = match fields {
        syn::Fields::Named(_) => "{",
        syn::Fields::Unnamed(_) => "(",
        syn::Fields::Unit => return String::new(),
    };
    let body: Vec<String> = fields_of(fields).into_iter().map(|f| format!("{}: {}", f.name, f.ty)).collect();
    format!("{open}{}", body.join(", "))
}

fn struct_shape(fields: &syn::Fields, attrs: &[Attribute]) -> Shape {
    let style = match fields {
        syn::Fields::Named(_) => Style::Named,
        syn::Fields::Unnamed(_) => Style::Tuple,
        syn::Fields::Unit => Style::Unit,
    };
    Shape::Struct { style, fields: fields_of(fields), non_exhaustive: has_attr(attrs, "non_exhaustive") }
}

/// The props struct `#[component]` generates for an inline-props fn, as a
/// literal-constructible named struct with one `pub` field per parameter.
/// `None` for the legacy single-`props`-struct form and generic components,
/// which `#[component]` leaves on the explicit-struct path (see
/// `runtime-macros-expand/src/inline_props.rs`).
fn component_props(f: &syn::ItemFn) -> Option<Shape> {
    let is_component =
        f.attrs.iter().any(|a| a.path().segments.last().is_some_and(|s| s.ident == "component"));
    if !is_component || !f.sig.generics.params.is_empty() {
        return None;
    }
    let inputs: Vec<&syn::PatType> = f
        .sig
        .inputs
        .iter()
        .filter_map(|a| match a {
            FnArg::Typed(pt) => Some(pt),
            FnArg::Receiver(_) => None,
        })
        .collect();
    if let [pt] = inputs.as_slice() {
        let named_props = matches!(&*pt.pat, Pat::Ident(pi) if pi.ident == "props");
        let ty = match &*pt.ty {
            Type::Reference(r) => &*r.elem,
            other => other,
        };
        let typed_props = matches!(ty, Type::Path(p)
            if p.path.segments.last().is_some_and(|s| s.ident.to_string().ends_with("Props")));
        if !has_attr(&pt.attrs, "prop") && (named_props || typed_props) {
            return None;
        }
    }
    let fields = inputs
        .iter()
        .filter_map(|pt| match &*pt.pat {
            Pat::Ident(pi) => Some(Field {
                name: pi.ident.to_string(),
                public: true,
                ty: pt.ty.to_token_stream().to_string(),
            }),
            _ => None,
        })
        .collect();
    Some(Shape::Struct { style: Style::Named, fields, non_exhaustive: false })
}

fn parent(p: &str) -> String {
    p.rsplit_once('/').map(|(d, _)| d.to_string()).unwrap_or_default()
}

fn join(dir: &str, rel: &str) -> String {
    if dir.is_empty() { rel.to_string() } else { format!("{dir}/{rel}") }
}

fn normalize(p: &str) -> String {
    let mut out: Vec<&str> = Vec::new();
    for seg in p.split('/') {
        match seg {
            "" | "." => {}
            ".." => {
                out.pop();
            }
            s => out.push(s),
        }
    }
    out.join("/")
}

