    /// End to end through git: both sides read with `cat-file --batch`
    /// (several files, so the reply parsing has to step over bodies), and
    /// an unchanged crate reports nothing.
    #[test]
    fn check_reads_both_revisions_from_git() {
        let dir = std::env::temp_dir().join(format!("registry-apitest-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(dir.join("crates/t/src")).unwrap();
        let git = |args: &[&str]| {
            let out = Command::new("git").args(args).current_dir(&dir).output().unwrap();
            assert!(out.status.success(), "git {args:?}: {}", String::from_utf8_lossy(&out.stderr));
            String::from_utf8_lossy(&out.stdout).trim().to_string()
        };
        git(&["init", "-q", "-b", "main"]);
        git(&["config", "user.email", "t@example.com"]);
        git(&["config", "user.name", "t"]);
        let write = |path: &str, body: &str| std::fs::write(dir.join(path), body).unwrap();
        write("crates/t/src/lib.rs", "mod cell;\npub use cell::TableCellProps;\n");
        write("crates/t/src/cell.rs", "pub struct TableCellProps {\n    pub span: u32,\n}\n");
        git(&["add", "-A"]);
        git(&["commit", "-qm", "feat: table"]);
        let released = git(&["rev-parse", "HEAD"]);
        assert!(check(&dir, "crates/t", "crates/t/src/lib.rs", &released).unwrap().is_empty());

        write("crates/t/src/cell.rs", "pub struct TableCellProps {\n    pub span: u32,\n    pub column: u32,\n}\n");
        git(&["add", "-A"]);
        git(&["commit", "-qm", "feat(table): column"]);
        let found = check(&dir, "crates/t", "crates/t/src/lib.rs", &released).unwrap();
        assert_eq!(found.len(), 1, "{found:?}");
        assert!(found[0].contains("added field `column` to `cell::TableCellProps`"), "{found:?}");

        std::fs::remove_dir_all(&dir).unwrap();
    }
