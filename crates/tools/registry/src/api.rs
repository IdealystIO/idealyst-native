//! Finding semver-breaking public API changes between two versions of a
//! crate's source.
//!
//! The plan classifies a crate's bump from its commit SUBJECTS, and a
//! subject is a sentence someone wrote. `table` 3.1.0 added
//! `pub column: Option<ColumnSpec>` to `TableCellProps` under a `feat:`
//! subject, shipped as a minor, and broke a downstream app that built the
//! struct with a literal: a struct whose fields are all `pub` and which is
//! not `#[non_exhaustive]` can be built by a literal in another crate, and
//! a literal must name every field. So the planner parses the crate's
//! source at its recorded release commit and at HEAD, and any change
//! below raises the crate to a major.
//!
//! `#[non_exhaustive]` is not the way out for props structs: it forbids a
//! literal from another crate even with `..Default::default()`, and `ui!`
//! builds props structs by literal.
//!
//! # What counts as breaking
//!
//! Over the crate's *exported* items (see "Reachability"):
//!
//! - an exported item removed — fn, struct, enum, union, trait, type alias,
//!   const, static, module, `#[macro_export]` macro, an inherent `pub` method
//!   or associated const on an exported type, or a `pub use` of another
//!   crate's item. An item that moved modules but is still exported under
//!   the same kind and name is not removed.
//! - on a struct: a `pub` field removed, made non-`pub`, or retyped. If the
//!   struct was literal-constructible (every field `pub`, no
//!   `#[non_exhaustive]`): any field added, a change between named / tuple /
//!   unit form, or `#[non_exhaustive]` added.
//! - on an enum: a variant removed or its fields changed. Unless the enum
//!   was `#[non_exhaustive]`: a variant added (every exhaustive `match` in
//!   a dependent's published version stops compiling), or
//!   `#[non_exhaustive]` added.
//! - on a trait: an item removed, or a required item (no default) added.
//!
//! Signature changes to functions are NOT detected — many are compatible
//! (`T` → `impl Into<T>`), and telling them apart needs type checking.
//!
//! # Reachability
//!
//! An item is exported when it is `pub` (exactly `pub`: `pub(crate)` and
//! `pub(super)` are not) and either every module on its path is `pub`, or a
//! `pub use` in an exported module names it — directly, or through a glob of
//! its module. This is a best-effort name resolver over `mod` declarations
//! and `use` paths starting at `crate`, `self`, `super` or a child module;
//! it does not expand macros. So:
//!
//! - an item generated by a macro is invisible, with one exception:
//!   `#[component]` fns. An inline-props component
//!   (`#[component] fn Badge(label: String)`) generates `pub struct
//!   BadgeProps` with one `pub` field per parameter, so a new parameter is a
//!   new field on a literal-constructible struct and is treated as such. A
//!   zero-parameter component is modelled as `BadgeProps` with no fields, so
//!   its first parameter is caught too. The legacy `props: &FooProps` form
//!   is skipped — its explicit `FooProps` struct is checked on its own.
//!   Generic components keep the legacy path and are skipped.
//! - `#[cfg]` is ignored: every module and item is read whatever its cfg.
//!   Two cfg-alternative items with the same name count once.
//! - a module file that does not exist (generated, or `include!`d) is
//!   skipped.
//!
//! False positives are possible (a `pub` item in a `pub` module the crate
//! documents as internal; a sealed trait gaining a required method). The
//! plan prints every finding so a human can read them, and
//! `--skip-api-check <CRATE>` waives the raise for one crate.

