//! Read/write the idealyst-managed compose file,
//! `.devcontainer/docker-compose.idealyst.yml`.
//!
//! This file is owned *entirely* by idealyst: we regenerate it wholesale on
//! every `apply`, so nothing here tries to preserve hand edits. The one piece
//! of state we read back is the `x-idealyst` metadata block — a `x-`-prefixed
//! top-level key Docker Compose ignores — which records exactly which
//! canonical services (and variants) are enabled. That's what lets a re-run
//! (CLI wizard or MCP) preselect the current set without reverse-engineering
//! it from the generated service definitions.

use std::path::{Path, PathBuf};

use anyhow::{Context, Result};
use serde_yaml::{Mapping, Value};

use super::service::{registry, Ctx};
use super::EnabledService;

/// Filename of the managed compose file, relative to `.devcontainer/`.
pub const MANAGED_FILE: &str = "docker-compose.idealyst.yml";

/// Schema version stamped into the `x-idealyst` block, so a future format
/// change can detect and migrate older files.
const STATE_VERSION: u64 = 1;

const HEADER: &str = "\
# Generated by `idealyst configure devcontainer` — MANAGED BY IDEALYST.
#
# This whole file is regenerated on every `idealyst configure devcontainer`
# run; manual edits here WILL be overwritten. To add your own services, edit
# `docker-compose.yml` (which idealyst never touches) instead.
#
# The `x-idealyst` block below records which idealyst-managed services are
# enabled — do not edit it by hand.
";

/// Absolute path to the managed file under `<dir>/.devcontainer/`.
pub fn managed_path(dir: &Path) -> PathBuf {
    dir.join(".devcontainer").join(MANAGED_FILE)
}

/// Read the enabled service set from an existing managed file. Returns an
/// empty vec if the file is missing or has no (readable) `x-idealyst` block.
pub fn read_enabled(dir: &Path) -> Result<Vec<EnabledService>> {
    let path = managed_path(dir);
    let Ok(text) = std::fs::read_to_string(&path) else {
        return Ok(Vec::new());
    };
    let doc: Value = serde_yaml::from_str(&text)
        .with_context(|| format!("parse managed compose file {}", path.display()))?;
    Ok(parse_enabled(&doc))
}

/// Extract the enabled list from the `x-idealyst.services` sequence.
fn parse_enabled(doc: &Value) -> Vec<EnabledService> {
    let Some(services) = doc
        .get("x-idealyst")
        .and_then(|x| x.get("services"))
        .and_then(|s| s.as_sequence())
    else {
        return Vec::new();
    };
    services
        .iter()
        .filter_map(|entry| {
            let id = entry.get("id")?.as_str()?.to_string();
            let variant = entry
                .get("variant")
                .and_then(|v| v.as_str())
                .map(|s| s.to_string());
            Some(EnabledService { id, variant })
        })
        .collect()
}

/// Render the full managed compose document for `enabled`, with connection
/// env + `depends_on` attached to `app_service`. Emitted in registry order
/// (not selection order) so the file is byte-stable for a given set.
pub fn render(enabled: &[EnabledService], app_service: &str) -> String {
    let ctx = Ctx { app_service: app_service.to_string() };

    // Walk the registry so output order is deterministic; look up each
    // registered service's requested variant from `enabled`.
    let mut state_services: Vec<Value> = Vec::new();
    let mut services_map = Mapping::new();
    let mut app_env = Mapping::new();
    let mut depends_on: Vec<Value> = Vec::new();
    let mut volumes_map = Mapping::new();

    for svc in registry() {
        let Some(en) = enabled.iter().find(|e| e.id == svc.id()) else {
            continue;
        };
        let variant = en.variant.as_deref().or_else(|| svc.default_variant());
        let frag = svc.fragment(variant, &ctx);

        // x-idealyst state entry.
        let mut entry = Mapping::new();
        entry.insert("id".into(), svc.id().into());
        if let Some(v) = &en.variant {
            entry.insert("variant".into(), v.as_str().into());
        }
        state_services.push(Value::Mapping(entry));

        // The service definition itself.
        services_map.insert(svc.id().into(), frag.service);

        // Merge env + dependency edge onto the app service.
        for (k, v) in frag.app_env {
            app_env.insert(k.into(), v.into());
        }
        depends_on.push(svc.id().into());

        // Declare top-level named volumes (null = default driver).
        for vol in frag.volumes {
            volumes_map.insert(vol.into(), Value::Null);
        }
    }

    // The partial app-service override — merged into the base compose file's
    // `<app_service>` by Docker Compose. Only carries what we contribute.
    if !app_env.is_empty() || !depends_on.is_empty() {
        let mut app = Mapping::new();
        if !app_env.is_empty() {
            app.insert("environment".into(), Value::Mapping(app_env));
        }
        if !depends_on.is_empty() {
            app.insert("depends_on".into(), Value::Sequence(depends_on));
        }
        services_map.insert(app_service.into(), Value::Mapping(app));
    }

    // Assemble the document. `x-idealyst` first so it reads as a header.
    let mut x_idealyst = Mapping::new();
    x_idealyst.insert("version".into(), STATE_VERSION.into());
    x_idealyst.insert("services".into(), Value::Sequence(state_services));

    let mut doc = Mapping::new();
    doc.insert("x-idealyst".into(), Value::Mapping(x_idealyst));
    doc.insert("services".into(), Value::Mapping(services_map));
    if !volumes_map.is_empty() {
        doc.insert("volumes".into(), Value::Mapping(volumes_map));
    }

    let body = serde_yaml::to_string(&Value::Mapping(doc)).expect("serialize managed compose");
    format!("{HEADER}{body}")
}
