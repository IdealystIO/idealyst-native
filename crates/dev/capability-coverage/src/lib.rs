//! Static capability coverage: which backends leave a capability-trait
//! method at its default body while another backend implements it.
//!
//! ## Why this exists
//!
//! Most `caps::*Ops` methods have a default body so a backend compiles
//! before it supports everything. Many of those defaults are silent
//! no-ops: `StyleOps::attach_states` lights no hover / press variant,
//! `TextInputOps::update_text_input_value` drops every value written from
//! code, `AppEnvOps::url_opener` makes `open_url` do nothing. A backend
//! that never overrides one compiles, renders, and quietly lacks the
//! feature — Windows shipped every one of those. Nothing at compile time
//! or in a backend's own tests notices, because the backend never
//! mentions the method.
//!
//! ## The rule
//!
//! A method is **flagged** on a backend when the trait gives it a default
//! body, the backend's impl of that trait does not override it, and at
//! least one other checked backend does. "Somebody implements it" is the
//! signal that the default is not the whole feature; a method no backend
//! overrides is a pure extension point and is never flagged.
//!
//! Every flag must be accounted for in `coverage.toml` (crate root) as
//! either `na` (the default IS right for that backend — no hover on a
//! touch screen, no soft keyboard on a desktop) or `gap` (missing, to be
//! implemented). The test fails on an unlisted flag and on a listed entry
//! that no longer flags (implemented since, or renamed), so the file stays
//! the truth.
//!
//! ## Why source scanning
//!
//! Every backend crate is `cfg`-gated to its own target (`backend-windows`
//! is an empty rlib off Windows), so no single build sees them all. Parsing
//! the source with `syn` checks every backend from any host, in CI, in
//! milliseconds. The cost: an impl generated by a macro is invisible. No
//! backend does that for capability traits today; a backend that starts
//! to will show as flags, loudly.

use std::collections::{BTreeMap, BTreeSet};
use std::fs;
use std::path::{Path, PathBuf};

use serde::Deserialize;
use syn::visit::Visit;

/// Trait name → method names. Trait names are bare (`StyleOps`): every
/// capability trait lives in `runtime_vocabulary::caps`, and backends
/// spell the path several ways (`caps::StyleOps`, an imported `StyleOps`).
pub type MethodMap = BTreeMap<String, BTreeSet<String>>;

/// A backend to check: a display name and its source root.
#[derive(Clone, Debug, Deserialize)]
pub struct Backend {
    pub name: String,
    /// Relative to the workspace root.
    pub src: PathBuf,
}

/// Why a flag is accepted.
#[derive(Clone, Copy, Debug, Deserialize, PartialEq, Eq, PartialOrd, Ord)]
#[serde(rename_all = "lowercase")]
pub enum Status {
    /// The default is correct for this backend.
    Na,
    /// Missing: the backend should implement it.
    Gap,
}

/// Accepted flags: `method` on each of `backends`.
///
/// `method` is `Trait::method`, `Trait::*` for every method of the
/// trait, or `*` for every method. `backends` names backends, or `"*"` for every checked backend
/// not in `except`. An exact entry (named method, named backends) must
/// match a flag for every backend it names; a wildcard entry must match
/// at least one flag — either way an entry that matches nothing is stale.
/// When several entries match a flag, an exact method beats `Trait::*`,
/// which beats `*`.
#[derive(Clone, Debug, Deserialize)]
pub struct Allow {
    pub method: String,
    pub backends: Vec<String>,
    #[serde(default)]
    pub except: Vec<String>,
    pub status: Status,
    pub reason: String,
}

impl Allow {
    fn wildcard(&self) -> bool {
        self.method == "*" || self.method.ends_with("::*") || self.backends.iter().any(|b| b == "*")
    }

    fn covers_method(&self, method: &str) -> bool {
        if self.method == "*" {
            return true;
        }
        match self.method.strip_suffix("::*") {
            Some(t) => method.split("::").next() == Some(t),
            None => self.method == method,
        }
    }

    fn covers_backend(&self, backend: &str) -> bool {
        !self.except.iter().any(|b| b == backend)
            && self.backends.iter().any(|b| b == "*" || b == backend)
    }

    pub fn covers(&self, flag: &Flag) -> bool {
        self.covers_method(&flag.method) && self.covers_backend(&flag.backend)
    }
}

/// `coverage.toml`.
#[derive(Clone, Debug, Deserialize)]
pub struct Config {
    /// The capability traits' source directory, relative to the workspace.
    pub caps: PathBuf,
    #[serde(rename = "backend")]
    pub backends: Vec<Backend>,
    #[serde(default, rename = "allow")]
    pub allows: Vec<Allow>,
}

impl Config {
    pub fn load(path: &Path) -> Result<Config, String> {
        let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
        toml::from_str(&text).map_err(|e| format!("{}: {e}", path.display()))
    }
}

/// Every `.rs` file under `dir`, sorted (deterministic reports).
fn rust_files(dir: &Path) -> Result<Vec<PathBuf>, String> {
    let mut out = Vec::new();
    let mut stack = vec![dir.to_path_buf()];
    while let Some(d) = stack.pop() {
        let entries = fs::read_dir(&d).map_err(|e| format!("{}: {e}", d.display()))?;
        for entry in entries {
            let path = entry.map_err(|e| e.to_string())?.path();
            if path.is_dir() {
                stack.push(path);
            } else if path.extension().is_some_and(|x| x == "rs") {
                out.push(path);
            }
        }
    }
    out.sort();
    Ok(out)
}

fn parse(path: &Path) -> Result<syn::File, String> {
    let text = fs::read_to_string(path).map_err(|e| format!("{}: {e}", path.display()))?;
    syn::parse_file(&text).map_err(|e| format!("{}: {e}", path.display()))
}

/// Capability traits under `caps_dir` and their methods that carry a
/// default body.
pub fn default_methods(caps_dir: &Path) -> Result<MethodMap, String> {
    struct V(MethodMap);
    impl<'a> Visit<'a> for V {
        fn visit_item_trait(&mut self, t: &'a syn::ItemTrait) {
            let methods = t
                .items
                .iter()
                .filter_map(|i| match i {
                    syn::TraitItem::Fn(f) if f.default.is_some() => Some(f.sig.ident.to_string()),
                    _ => None,
                })
                .collect();
            self.0.insert(t.ident.to_string(), methods);
        }
    }
    let mut v = V(MethodMap::new());
    for f in rust_files(caps_dir)? {
        v.visit_file(&parse(&f)?);
    }
    Ok(v.0)
}

/// For each trait in `traits`, the methods a backend's `impl Trait for …`
/// blocks under `src` define (nested modules included). A trait the
/// backend never implements is absent from the map.
pub fn overrides(src: &Path, traits: &BTreeSet<String>) -> Result<MethodMap, String> {
    struct V<'t> {
        traits: &'t BTreeSet<String>,
        out: MethodMap,
    }
    impl<'a> Visit<'a> for V<'_> {
        fn visit_item_impl(&mut self, i: &'a syn::ItemImpl) {
            if let Some((_, path, _)) = &i.trait_ {
                let name = path.segments.last().map(|s| s.ident.to_string()).unwrap_or_default();
                if self.traits.contains(&name) {
                    let set = self.out.entry(name).or_default();
                    for item in &i.items {
                        if let syn::ImplItem::Fn(f) = item {
                            set.insert(f.sig.ident.to_string());
                        }
                    }
                }
            }
            syn::visit::visit_item_impl(self, i);
        }
    }
    let mut v = V { traits, out: MethodMap::new() };
    for f in rust_files(src)? {
        v.visit_file(&parse(&f)?);
    }
    Ok(v.out)
}

/// The scan: per backend, per trait, which default-bodied methods it
/// overrides.
#[derive(Debug)]
pub struct Coverage {
    pub defaults: MethodMap,
    /// Backend name → its overrides, in config order.
    pub backends: Vec<(String, MethodMap)>,
}

/// One flagged `(backend, Trait::method)`.
#[derive(Clone, Debug, PartialEq, Eq, PartialOrd, Ord)]
pub struct Flag {
    pub backend: String,
    pub method: String,
}

impl Coverage {
    pub fn scan(workspace: &Path, config: &Config) -> Result<Coverage, String> {
        let defaults = default_methods(&workspace.join(&config.caps))?;
        let traits: BTreeSet<String> = defaults.keys().cloned().collect();
        let mut backends = Vec::new();
        for b in &config.backends {
            backends.push((b.name.clone(), overrides(&workspace.join(&b.src), &traits)?));
        }
        Ok(Coverage { defaults, backends })
    }

    /// Whether `backend` overrides `trait_::method`.
    pub fn implements(&self, backend: &str, trait_: &str, method: &str) -> bool {
        self.backends
            .iter()
            .find(|(n, _)| n == backend)
            .and_then(|(_, m)| m.get(trait_))
            .is_some_and(|s| s.contains(method))
    }

    /// Default-bodied methods at least one backend overrides, as
    /// `(trait, method)`.
    pub fn contested(&self) -> Vec<(String, String)> {
        let mut out = Vec::new();
        for (t, methods) in &self.defaults {
            for m in methods {
                if self.backends.iter().any(|(b, _)| self.implements(b, t, m)) {
                    out.push((t.clone(), m.clone()));
                }
            }
        }
        out
    }

    /// Every flag (see the module docs for the rule).
    pub fn flags(&self) -> Vec<Flag> {
        let mut out = Vec::new();
        for (t, m) in self.contested() {
            for (b, _) in &self.backends {
                if !self.implements(b, &t, &m) {
                    out.push(Flag { backend: b.clone(), method: format!("{t}::{m}") });
                }
            }
        }
        out.sort();
        out
    }
}

/// What the allowlist says about a flag set.
#[derive(Debug, Default)]
pub struct Verdict {
    /// Flagged and not listed: a new silent gap.
    pub unlisted: Vec<Flag>,
    /// Listed but not flagged: implemented since, or a stale name. A
    /// wildcard entry that matches nothing is reported with its own
    /// `method` / first backend.
    pub stale: Vec<Flag>,
    /// Listed entries naming a backend the config does not check.
    pub unknown_backends: Vec<String>,
}

impl Verdict {
    pub fn ok(&self) -> bool {
        self.unlisted.is_empty() && self.stale.is_empty() && self.unknown_backends.is_empty()
    }
}

pub fn check(coverage: &Coverage, config: &Config) -> Verdict {
    let flags = coverage.flags();
    let names: BTreeSet<&str> = config.backends.iter().map(|b| b.name.as_str()).collect();
    let mut verdict = Verdict::default();
    for a in &config.allows {
        for b in a.backends.iter().chain(&a.except) {
            if b != "*" && !names.contains(b.as_str()) {
                verdict.unknown_backends.push(format!("{b} (in `{}`)", a.method));
            }
        }
        if a.wildcard() {
            if !flags.iter().any(|f| a.covers(f)) {
                let backend = a.backends.first().cloned().unwrap_or_default();
                verdict.stale.push(Flag { backend, method: a.method.clone() });
            }
        } else {
            for b in &a.backends {
                let f = Flag { backend: b.clone(), method: a.method.clone() };
                if names.contains(b.as_str()) && !flags.contains(&f) {
                    verdict.stale.push(f);
                }
            }
        }
    }
    verdict.unlisted = flags.into_iter().filter(|f| allowed(config, f).is_none()).collect();
    verdict
}

/// The allowlist entry covering `flag`, if any: exact method first, then
/// `Trait::*`, then `*`.
pub fn allowed<'c>(config: &'c Config, flag: &Flag) -> Option<&'c Allow> {
    let matching = || config.allows.iter().filter(|a| a.covers(flag));
    let exact = |a: &&Allow| !a.method.ends_with('*');
    let by_trait = |a: &&Allow| a.method.ends_with("::*");
    matching().find(exact).or_else(|| matching().find(by_trait)).or_else(|| matching().next())
}

/// A Markdown matrix of every contested method: `✓` implemented, `—` the
/// default is right (na), `✗` a listed gap, `?` unlisted.
pub fn markdown(coverage: &Coverage, config: &Config) -> String {
    let mut s = String::from("| method |");
    for (b, _) in &coverage.backends {
        s.push_str(&format!(" {b} |"));
    }
    s.push_str("\n|---|");
    for _ in &coverage.backends {
        s.push_str(":-:|");
    }
    s.push('\n');
    for (t, m) in coverage.contested() {
        s.push_str(&format!("| `{t}::{m}` |"));
        for (b, _) in &coverage.backends {
            let cell = if coverage.implements(b, &t, &m) {
                "✓"
            } else {
                let flag = Flag { backend: b.clone(), method: format!("{t}::{m}") };
                match allowed(config, &flag).map(|a| a.status) {
                    Some(Status::Na) => "—",
                    Some(Status::Gap) => "✗",
                    None => "?",
                }
            };
            s.push_str(&format!(" {cell} |"));
        }
        s.push('\n');
    }
    s
}

/// The workspace root (this crate is `crates/dev/capability-coverage`).
